#!/bin/zsh
# Keeps ioswitch's XNU changes in the main repository as one patch.
#
# The XNU checkout (out/native-a57/root-v1/tree/.cache/xnu-work) is its own git repository: apple's xnu-10063.141.1
# at BASE, with our changes committed on its local branch `ioswitch`. The main repository ignores .cache/, so this
# script writes that branch's whole difference from BASE to $PATCH, which the main repository tracks.
#
#   scripts/xnu-patch.sh export          write $PATCH from the ioswitch branch (refuses while XNU has uncommitted edits)
#   scripts/xnu-patch.sh check           exit 1 if $PATCH differs from what export would write
#   scripts/xnu-patch.sh apply <xnu>     apply $PATCH to a clean xnu-10063.141.1 checkout and commit it as `ioswitch`
#
# Commit XNU edits in .cache/xnu-work first (git -C <xnu-work> commit -a), then export, then commit the main repo.
set -eu
ROOT=${0:A:h:h}
XNU=$ROOT/out/native-a57/root-v1/tree/.cache/xnu-work
PATCH=$ROOT/out/native-a57/root-v1/tree/patches/xnu-ioswitch.diff
BASE=d8b8029   # xnu-10063.141.1, the checkout's first commit

render() {
  print "# ioswitch's changes to apple-oss-distributions/xnu tag xnu-10063.141.1 (base commit $BASE in .cache/xnu-work)."
  print "# Generated by scripts/xnu-patch.sh export from branch ioswitch at $(git -C $XNU rev-parse --short ioswitch); apply with"
  print "# scripts/xnu-patch.sh apply <xnu checkout>. Do not edit by hand."
  git -C $XNU diff --binary --full-index $BASE ioswitch
}

case ${1:-} in
  export)
    if [[ -n $(git -C $XNU status --porcelain) ]]; then
      print -u2 "$XNU has uncommitted changes: commit them on branch ioswitch first"
      exit 1
    fi
    render > $PATCH.new
    mv $PATCH.new $PATCH
    print "$PATCH: $(git -C $XNU diff --shortstat $BASE ioswitch)"
    ;;
  check)
    if ! render | cmp -s - $PATCH; then
      print -u2 "$PATCH is out of date: run scripts/xnu-patch.sh export"
      exit 1
    fi
    ;;
  apply)
    target=${2:?usage: xnu-patch.sh apply <xnu-10063.141.1 checkout>}
    git -C $target diff --quiet && git -C $target diff --cached --quiet || { print -u2 "$target is not clean"; exit 1; }
    git -C $target switch -c ioswitch
    git -C $target apply --index --whitespace=nowarn $PATCH
    git -C $target commit -q -m "ioswitch: Switch (Tegra X1) port changes (from $PATCH)"
    print "applied to $target on branch ioswitch"
    ;;
  *)
    sed -n '2,13p' $0
    exit 2
    ;;
esac
