#!/usr/bin/env python3
"""Prepare immutable expectations for a bounded native FAT32 read experiment.

This writes local fixture/manifest/header files only. Existing disk parts stay
unchanged; a separately reviewed installer must provision the SD files.
"""
from __future__ import annotations

import argparse
import hashlib
import json
from pathlib import Path
import struct
import sys

sys.path.insert(0, str(Path(__file__).resolve().parent))
from split_volume import SplitVolume

ROOT = Path(__file__).resolve().parents[1]
FIXTURE_SIZE = 131777
FIXTURE_PATH = "IOSWITCH/VERIFY.BIN"
PART_BYTES = 4_000_000_000


def digest(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def c_bytes(hex_digest: str) -> str:
    return "{" + ",".join("0x" + hex_digest[i:i + 2] for i in range(0, 64, 2)) + "}"


def build(media: Path, output: Path) -> dict:
    if output.exists() or output.is_symlink():
        raise ValueError("output already exists")
    volumes = [SplitVolume(media / name) for name in ("os", "systemos")]
    verified = [volume.verify() for volume in volumes]
    if [v.size for v in volumes] != [6_077_580_800, 3_303_014_400]:
        raise ValueError("unexpected donor disk sizes")
    if any(v.part_bytes != PART_BYTES for v in volumes):
        raise ValueError("expected the reviewed 4,000,000,000-byte split")
    fixture = b"".join(hashlib.sha256(b"IOSwitch native file fixture v1\0" +
                                   struct.pack("<I", n)).digest()
                       for n in range((FIXTURE_SIZE + 31) // 32))[:FIXTURE_SIZE]
    files = []
    volume_records = []
    for index, (name, volume) in enumerate(zip(("OS", "SYSTEMOS"), volumes)):
        parts = []
        for part_index, part in enumerate(volume.manifest["parts"]):
            path = f"IOSWITCH/{name}/PART{part_index:04d}.BIN"
            item = {"path": path, "offset": part["offset"],
                    "size_bytes": part["size_bytes"], "sha256": part["sha256"],
                    "source": str(volume.paths[part_index].resolve())}
            files.append(item)
            parts.append(item)
        volume_records.append({"index": index, "name": name,
                               "size_bytes": volume.size, "parts": parts,
                               "sha256": volume.manifest["sha256"]})
    # Include unaligned reads, sectors near both ends, a large logical offset,
    # and a single read crossing the actual OS part boundary.
    positions = [
        (0, 0, 4096), (0, 1 << 20, 4096), (0, (64 << 20) + 37, 8192),
        (0, 2_000_000_000 - 2048, 4096), (0, PART_BYTES - 2048, 4096),
        (0, volumes[0].size - 4096, 4096),
        (1, 0, 4096), (1, 1 << 20, 4096), (1, (1 << 30) + 17, 8192),
        (1, volumes[1].size - 4096, 4096),
    ]
    ranges = [{"volume_index": index, "offset": offset, "length": size,
               "sha256": digest(volumes[index].read_at(offset, size))}
              for index, offset, size in positions]
    manifest = {
        "schema": "ioswitch-native-files-v1",
        "purpose": "Full small-fixture hash and bounded samples of real split disk files",
        "runtime_complete_volume_hash": False,
        "fixture": {"path": FIXTURE_PATH, "size_bytes": len(fixture),
                    "sha256": digest(fixture)},
        "volumes": volume_records, "ranges": ranges,
        "host_complete_volume_verification": verified,
        "runtime_sample_bytes": sum(r["length"] for r in ranges),
        "native_file_access_verified": False,
        "proof_boundary": "Expectations only; no device access, FAT mount or native file read performed.",
    }
    header = ["/* Generated by scripts/native_storage_fixture.py; immutable build input. */",
              "#ifndef IOSWITCH_MEDIA_EXPECTATIONS_H", "#define IOSWITCH_MEDIA_EXPECTATIONS_H",
              "#include <stdint.h>",
              "struct iosw_expected_part { const char *path; uint64_t size_bytes; };",
              "struct iosw_expected_volume { const char *name; uint64_t size_bytes; uint32_t part_count; const struct iosw_expected_part *parts; };",
              "struct iosw_expected_range { uint32_t volume_index; uint64_t offset; uint32_t length; uint8_t sha256[32]; };",
              f"#define IOSW_STORAGE_FIXTURE_PATH {json.dumps(FIXTURE_PATH)}",
              f"#define IOSW_STORAGE_FIXTURE_SIZE {len(fixture)}u",
              "static const uint8_t iosw_storage_fixture_sha256[32]=" + c_bytes(digest(fixture)) + ";"]
    for index, volume in enumerate(volume_records):
        header.append(f"static const struct iosw_expected_part iosw_storage_parts_{index}[]={{")
        header.extend("{" + json.dumps(p["path"]) + ",UINT64_C(" + str(p["size_bytes"]) + ")},"
                      for p in volume["parts"])
        header.append("};")
    header.append("static const struct iosw_expected_volume iosw_storage_volumes[]={")
    header.extend("{" + json.dumps(v["name"]) + ",UINT64_C(" + str(v["size_bytes"]) + ")," +
                  str(len(v["parts"])) + ",iosw_storage_parts_" + str(v["index"]) + "},"
                  for v in volume_records)
    header.extend(["};", "static const struct iosw_expected_range iosw_storage_ranges[]={"])
    header.extend("{" + str(r["volume_index"]) + ",UINT64_C(" + str(r["offset"]) + ")," +
                  str(r["length"]) + "," + c_bytes(r["sha256"]) + "}," for r in ranges)
    header.extend(["};", "#define IOSW_STORAGE_VOLUME_COUNT 2u",
                   f"#define IOSW_STORAGE_RANGE_COUNT {len(ranges)}u", "#endif", ""])
    header_data = "\n".join(header).encode()
    manifest["header_sha256"] = digest(header_data)
    output.mkdir(parents=True, exist_ok=False)
    (output / "VERIFY.BIN").write_bytes(fixture)
    (output / "expectations.h").write_bytes(header_data)
    (output / "manifest.json").write_text(json.dumps(manifest, indent=2) + "\n")
    return manifest


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--media", type=Path, default=ROOT / "out/native-media")
    parser.add_argument("--output", type=Path, required=True)
    args = parser.parse_args()
    result = build(args.media, args.output)
    print(json.dumps({"files": 1 + sum(len(v["parts"]) for v in result["volumes"]),
                      "fixture_bytes": result["fixture"]["size_bytes"],
                      "ranges": len(result["ranges"]),
                      "runtime_sample_bytes": result["runtime_sample_bytes"],
                      "host_whole_volumes_verified": len(result["host_complete_volume_verification"])}))
