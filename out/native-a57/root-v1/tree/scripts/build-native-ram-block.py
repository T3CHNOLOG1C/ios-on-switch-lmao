#!/usr/bin/env python3
"""Pin one disposable packed Data seed and compile its bounded native RAM driver.

The host computes SHA-256 over the complete decoded logical disk. The device
hashes only the exact encoded seed and validates its packed geometry, then
returns the paired compiled logical digest. Neither digest proves Apple trust.
This command does not mount media, create a kernel, install or operate hardware.
"""
import argparse
import hashlib
import json
from pathlib import Path
import struct
import subprocess
import sys
import uuid

ROOT = Path(__file__).resolve().parents[1]
PAGE = 4096
RESIDENT_LIMIT = 128 << 20


def seed_metadata(path, volume_uuid):
    data = path.read_bytes()
    if not 32 <= len(data) <= 32 << 20 or data[:8] != b'DBRDISK1':
        raise ValueError('Expected bounded DBRDISK1 input')
    version, block, logical, count = struct.unpack_from('<IIQQ', data, 8)
    if version != 1 or block != PAGE or not 0 < logical <= 1 << 30 or logical % PAGE or count > 65536 or count > (len(data)-32)//16:
        raise ValueError('Invalid or unsupported packed seed geometry')
    canonical_uuid = str(uuid.UUID(volume_uuid)).upper()
    cursor, end, nonzero = 32 + count * 16, 0, 0
    extents = []
    digest = hashlib.sha256()
    zeros = bytes(1 << 20)

    def zero_run(length):
        while length:
            n = min(length, len(zeros))
            digest.update(memoryview(zeros)[:n])
            length -= n

    for index in range(count):
        at, size = struct.unpack_from('<QQ', data, 32 + index * 16)
        if not size or (at | size) % PAGE or at < end or at > logical or size > logical-at or size > len(data)-cursor:
            raise ValueError('Invalid packed extent')
        zero_run(at-end)
        chunk = memoryview(data)[cursor:cursor+size]
        digest.update(chunk)
        nonzero += sum(any(chunk[i:i+PAGE]) for i in range(0, size, PAGE))
        extents.append({'logical_offset': at, 'bytes': size, 'encoded_offset': cursor})
        cursor += size
        end = at + size
    if cursor != len(data) or nonzero * PAGE > RESIDENT_LIMIT:
        raise ValueError('Trailing input or resident seed cap exceeded')
    zero_run(logical-end)
    return dict(format='IOSwitchNativeDataSeed-v1', seed_path=str(path.resolve()),
                expected_volume_uuid=canonical_uuid, encoded_bytes=len(data),
                encoded_sha256=hashlib.sha256(data).hexdigest(), logical_bytes=logical,
                logical_sha256=digest.hexdigest(), extents=extents, nonzero_pages=nonzero,
                initial_resident_bytes=nonzero*PAGE, resident_limit_bytes=RESIDENT_LIMIT,
                pointer_table_bytes=logical//PAGE*8, request_scratch_bytes=65536,
                runtime_hash='encoded SHA256 only; full logical SHA256 computed on host and compiled as paired metadata',
                mutable=True, persistent=False, apple_authenticated=False,
                uuid_binding='expected IOMedia UUID must match uniquely under this live typed provider')


def seed_header(metadata):
    def array(value):
        return ','.join('0x'+value[i:i+2] for i in range(0, len(value), 2))
    return '\n'.join([
        '// Generated by build-native-ram-block.py from the exact recorded seed.',
        '#pragma once', '#include <stdint.h>',
        f'constexpr uint64_t kNativeDataSeedEncodedBytes = {metadata["encoded_bytes"]}ULL;',
        f'constexpr uint64_t kNativeDataSeedLogicalBytes = {metadata["logical_bytes"]}ULL;',
        f'constexpr uint64_t kNativeDataSeedNonzeroPages = {metadata["nonzero_pages"]}ULL;',
        f'constexpr char kNativeDataSeedUUID[] = "{metadata["expected_volume_uuid"]}";',
        f'constexpr uint8_t kNativeDataSeedEncodedSHA256[32] = {{{array(metadata["encoded_sha256"])}}};',
        f'constexpr uint8_t kNativeDataSeedLogicalSHA256[32] = {{{array(metadata["logical_sha256"])}}};', ''])


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--seed', required=True, type=Path)
    parser.add_argument('--uuid', required=True, help='Expected unique APFS Data volume UUID')
    parser.add_argument('--out', type=Path, default=ROOT/'build/native-ram-block')
    parser.add_argument('--pins-only', action='store_true', help='Write metadata/header without compiling')
    args = parser.parse_args()
    try:
        metadata = seed_metadata(args.seed.resolve(), args.uuid)
    except (ValueError, OSError, struct.error) as error:
        parser.error(str(error))
    out = args.out.resolve()
    out.mkdir(parents=True, exist_ok=True)
    header = out/'NativeDataSeed.h'
    header.write_text(seed_header(metadata))
    metadata['header_sha256'] = hashlib.sha256(header.read_bytes()).hexdigest()
    (out/'seed.json').write_text(json.dumps(metadata, indent=2)+'\n')
    if args.pins_only:
        print(json.dumps(metadata, indent=2))
        return
    recipe = ROOT/'build/xnu/ios-obj/DEVELOPMENT_ARM64_BCM2837/iokit/DEVELOPMENT/IOPlatformExpert.cpo.json'
    record = json.loads(recipe.read_text().strip().rstrip(','))
    source = ROOT/'drivers/NativeRamBlock/NativeRamBlock.cpp'
    destination = out/'NativeRamBlock.o'
    command, arguments, i = [], record['arguments'], 0
    while i < len(arguments):
        value = arguments[i]
        if value == record['file']:
            command.append(str(source))
        elif value == '-o':
            command += ['-o', str(destination)]
            i += 1
        elif value == '-Xclang' and arguments[i+1].startswith('-W'):
            i += 1
        elif not value.startswith(('-W', '-mcpu=', '-march=', '-flto')):
            command.append(value)
        i += 1
    command += ['-Wall', '-Wextra', '-Werror', '-Wno-unused-parameter',
                '-Wno-c99-designator', '-Wno-reorder-init-list', '-Wno-deprecated-enum-enum-conversion',
                '-Wno-unnecessary-virtual-specifier', '-march=armv8-a', '-mgeneral-regs-only', '-fno-lto',
                '-I', str(ROOT/'.cache/xnu-work/osfmk'), '-I', str(ROOT/'build/storage-abi/include'), '-I', str(out)]
    (out/'compile-command.json').write_text(json.dumps(command, indent=2)+'\n')
    result = subprocess.run(command, cwd=record['directory'], capture_output=True, text=True)
    (out/'compile.log').write_text(result.stdout+result.stderr)
    if result.returncode:
        raise SystemExit((result.stdout+result.stderr)[-7000:])
    data = destination.read_bytes()
    if struct.unpack_from('<4I', data) != (0xfeedfacf, 0x100000c, 0, 1):
        raise SystemExit('Expected ordinary arm64 Mach-O object')
    offset, deployment = 32, None
    for _ in range(struct.unpack_from('<I', data, 16)[0]):
        kind, length = struct.unpack_from('<II', data, offset)
        if kind == 0x32:
            deployment = struct.unpack_from('<II', data, offset+8)
        offset += length
    if deployment != (2, 0x110000):
        raise SystemExit(f'Unexpected deployment {deployment}')
    subprocess.run([sys.executable, ROOT/'scripts/build-native-virtio-bindings.py', '--component',
                    'NativeRamBlock', '--directory', out], check=True)
    sources = {str(p.relative_to(ROOT)): hashlib.sha256(p.read_bytes()).hexdigest()
               for p in [source, source.with_name('SparseDisk.h'), Path(__file__)]}
    report = dict(seed=metadata, sources=sources, object_sha256=hashlib.sha256(data).hexdigest(),
                  archive_sha256=hashlib.sha256((out/'libNativeRamBlock.a').read_bytes()).hexdigest(),
                  abi=json.loads((out/'bindings.json').read_text()), target='ARMv8-A, general registers only',
                  hardware_qualified=False, kernel_link_qualified=False)
    (out/'build.json').write_text(json.dumps(report, indent=2)+'\n')
    print(f'PASS: bounded RAM Data driver compiled; {metadata["initial_resident_bytes"]} resident seed bytes, '
          f'{metadata["pointer_table_bytes"]} pointer bytes, {metadata["logical_bytes"]} logical bytes')


if __name__ == '__main__':
    main()
