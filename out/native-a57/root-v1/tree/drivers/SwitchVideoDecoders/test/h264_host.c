// Host test for the H.264 half of AVD.videodecoder: runs H264Syntax/H264NVDEC over an Annex-B stream with a fake
// NVDEC backend and checks every submit with the kernel's checker (TegraNVDECCheck.h).
//   h264_host <stream.264>             prints "out <decode index> <poc>" in display order (compare with ffprobe)
//   h264_host <stream.264> --selftest  prints the first picture's submit as the kernel's N3 test vector (C source)
// Build: cc -O1 -I.. -o h264_host h264_host.c ../AVD/H264Syntax.c ../AVD/H264NVDEC.c
#include <stdio.h>
#include <stdlib.h>
#include <string.h>
#include "../AVD/H264NVDEC.h"
#include "../../TegraNVDEC/TegraNVDECCheck.h"

typedef struct {
    uint8_t *va[64];
    uint64_t size[64];
    unsigned decoded, failures;
    int selftest;
} Fake;

static int fakeAlloc(void *ctx, uint64_t size, uint32_t *handle, void **va)
{
    Fake *f = ctx;
    for (uint32_t h = 1; h < 64; h++) {
        if (f->va[h]) continue;
        f->va[h] = calloc(1, size);
        f->size[h] = size;
        *handle = h;
        *va = f->va[h];
        return f->va[h] ? 0 : -1;
    }
    return -1;
}

static void fakeFree(void *ctx, uint32_t handle)
{
    Fake *f = ctx;
    free(f->va[handle]);
    f->va[handle] = NULL;
}

static void dump(const char *name, const uint8_t *p, size_t n)
{
    printf("static const uint8_t %s[%zu] = {", name, n);
    for (size_t i = 0; i < n; i++) printf("%s0x%02x,", i % 16 ? " " : "\n    ", p[i]);
    printf("\n};\n");
}

static int fakeSubmit(void *ctx, const TegraNVDECSubmit *s, uint32_t *fence)
{
    Fake *f = ctx;
    uint64_t avail[TEGRA_NVDEC_MAX_ENTRIES] = {0};
    for (uint32_t i = 0; i < s->entry_count; i++) {
        const TegraNVDECEntry *e = &s->entries[i];
        if (e->kind != TEGRA_NVDEC_ENTRY_RELOC) continue;
        if (e->value >= 64 || !f->va[e->value] || e->offset > f->size[e->value]) {
            fprintf(stderr, "bad relocation %u\n", i);
            return -1;
        }
        avail[i] = f->size[e->value] - e->offset;
    }
    const char *why = tegra_nvdec_check(s, avail);
    if (why) {
        fprintf(stderr, "kernel check refuses picture %u: %s\n", f->decoded, why);
        f->failures++;
        return -1;
    }
    if (f->selftest == 1) {
        // The kernel test recreates the buffers itself: emit the setup, the bitstream and the slice offsets.
        const nvdec_h264_pic_s *p = (const nvdec_h264_pic_s *)s->setup;
        const TegraNVDECEntry *in = NULL, *sl = NULL;
        for (uint32_t i = 0; i < s->entry_count; i++) {
            if (s->entries[i].method == NVC5B0_SET_IN_BUF_BASE_OFFSET) in = &s->entries[i];
            if (s->entries[i].method == NVC5B0_SET_SLICE_OFFSETS_BUF_OFFSET) sl = &s->entries[i];
        }
        printf("// Generated by SwitchVideoDecoders/test/h264_host --selftest; do not edit.\n");
        printf("static const uint32_t kTestWidthMbs = %d, kTestHeightMbs = %d, kTestSlices = %u;\n", p->PicWidthInMbs,
               p->FrameHeightInMbs, p->slice_count);
        dump("kTestSetup", s->setup, s->setup_bytes);
        dump("kTestBitstream", f->va[in->value] + in->offset, p->stream_len);
        dump("kTestSliceOffsets", f->va[sl->value] + sl->offset, (p->slice_count + 1) * 4);
        f->selftest = 2;
    }
    *fence = f->decoded;
    return 0;
}

static int fakeWait(void *ctx, const TegraNVDECWait *w)
{
    (void)ctx, (void)w;
    return 0;
}

typedef struct {
    unsigned index;
    int32_t poc;
} Item;

static void *fakeDecoded(void *ctx, const H264Picture *pic)
{
    Fake *f = ctx;
    Item *it = malloc(sizeof(*it));
    it->index = (unsigned)(uintptr_t)pic->token;
    it->poc = pic->poc;
    f->decoded++;
    return it;
}

static void fakeEmit(void *ctx, void *item)
{
    Fake *f = ctx;
    Item *it = item;
    if (!f->selftest) printf("out %u %d\n", it->index, it->poc);
    free(it);
}

static void fakeDiscard(void *ctx, void *item)
{
    (void)ctx, free(item);
}

int main(int argc, char **argv)
{
    if (argc < 2) return 2;
    FILE *fp = fopen(argv[1], "rb");
    if (!fp) return 2;
    static uint8_t data[64 << 20];
    const size_t size = fread(data, 1, sizeof(data), fp);
    fclose(fp);
    Fake fake = {.selftest = argc > 2 && !strcmp(argv[2], "--selftest")};
    const H264Backend backend = {&fake, fakeAlloc, fakeFree, fakeSubmit, fakeWait, fakeDecoded, fakeEmit, fakeDiscard};
    H264Decoder *d = h264_decoder_create(&backend);

    // Split into NAL units, then access units (7.4.1.2.3: a new one starts at an AUD, a parameter set or SEI after
    // slices, or a slice with first_mb_in_slice 0); re-pack each as 4-byte length-prefixed NAL units.
    size_t starts[1 << 16], ends[1 << 16], count = 0;
    for (size_t i = 0; i + 3 <= size && count < (1 << 16);) {
        if (data[i] == 0 && data[i + 1] == 0 && data[i + 2] == 1) {
            if (count) {
                size_t e = i;
                while (e > starts[count - 1] && !data[e - 1]) e--;
                ends[count - 1] = e;
            }
            starts[count++] = i + 3;
            i += 3;
        } else {
            i++;
        }
    }
    if (!count) return 2;
    ends[count - 1] = size;
    for (size_t i = 0; i < count; i++) {
        const uint8_t t = data[starts[i]] & 0x1f;
        if (t == H264_NAL_SPS || t == H264_NAL_PPS)
            h264_decoder_parameter_set(d, data + starts[i], ends[i] - starts[i]);
    }
    if (h264_decoder_configure(d)) {
        fprintf(stderr, "configure refused the stream\n");
        return 1;
    }
    static uint8_t au[16 << 20];
    size_t auSize = 0;
    bool slices = false;
    unsigned index = 0;
    int errors = 0;
    for (size_t i = 0; i <= count; i++) {
        bool boundary = i == count;
        if (!boundary) {
            const uint8_t t = data[starts[i]] & 0x1f;
            if (slices && (t == 9 || t == H264_NAL_SPS || t == H264_NAL_PPS || t == H264_NAL_SEI)) boundary = true;
            if (slices && (t == 1 || t == 5) && (data[starts[i] + 1] & 0x80)) boundary = true;  // ue(first_mb) == 0
        }
        if (boundary && slices) {
            const int r = h264_decoder_decode(d, au, auSize, 4, (void *)(uintptr_t)index++, true);
            if (r < 0) {
                fprintf(stderr, "decode failed at access unit %u (%d)\n", index - 1, r);
                errors++;
            }
            auSize = 0;
            slices = false;
            if (fake.selftest == 2) break;
        }
        if (i == count) break;
        const size_t n = ends[i] - starts[i];
        au[auSize] = (uint8_t)(n >> 24), au[auSize + 1] = (uint8_t)(n >> 16);
        au[auSize + 2] = (uint8_t)(n >> 8), au[auSize + 3] = (uint8_t)n;
        memcpy(au + auSize + 4, data + starts[i], n);
        auSize += n + 4;
        const uint8_t t = data[starts[i]] & 0x1f;
        if (t == 1 || t == 5) slices = true;
    }
    h264_decoder_flush(d);
    h264_decoder_destroy(d);
    if (!fake.selftest)
        fprintf(stderr, "%u access units, %u pictures, %d errors, %u refused\n", index, fake.decoded, errors,
                fake.failures);
    return errors || fake.failures ? 1 : 0;
}
