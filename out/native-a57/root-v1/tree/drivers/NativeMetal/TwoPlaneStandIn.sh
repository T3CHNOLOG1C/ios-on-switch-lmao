#!/bin/sh
# Regenerates TwoPlaneStandIn.h from TwoPlaneStandIn.metal: AIR for iOS 17, which the device's runtime translates as it does any
# app's library (the iOS SDK's Metal toolchain, `xcrun -sdk iphoneos metal`).
set -e
cd "$(dirname "$0")"
work=$(mktemp -d)
trap 'rm -f "$work/TwoPlaneStandIn.air" "$work/TwoPlaneStandIn.metallib"; rmdir "$work"' EXIT
xcrun -sdk iphoneos metal -target air64-apple-ios17.0 -O2 -c TwoPlaneStandIn.metal -o "$work/TwoPlaneStandIn.air"
xcrun -sdk iphoneos metallib "$work/TwoPlaneStandIn.air" -o "$work/TwoPlaneStandIn.metallib"
{
  echo "// Generated by TwoPlaneStandIn.sh from TwoPlaneStandIn.metal: do not edit."
  echo "static const unsigned char kTwoPlaneStandInLibrary[] = {"
  xxd -i < "$work/TwoPlaneStandIn.metallib"
  echo "};"
} > TwoPlaneStandIn.h
