"""data_seed.py SEED.dbr UUID OUT.h: NativeDataSeed.h for NativeRamBlock (tree/scripts/build-native-ram-block.py
--pins-only): the packed seed's geometry and its encoded and logical SHA-256s, compiled into the driver.
"""

import hashlib
import struct
import sys
import uuid
from pathlib import Path

PAGE = 4096
RESIDENT_LIMIT = 128 << 20


def seed_metadata(path, volume_uuid):
    data = Path(path).read_bytes()
    if not 32 <= len(data) <= 32 << 20 or data[:8] != b'DBRDISK1':
        raise ValueError('Expected bounded DBRDISK1 input')
    version, block, logical, count = struct.unpack_from('<IIQQ', data, 8)
    if (
        version != 1
        or block != PAGE
        or not 0 < logical <= 1 << 30
        or logical % PAGE
        or count > 65536
        or count > (len(data) - 32) // 16
    ):
        raise ValueError('Invalid or unsupported packed seed geometry')
    canonical_uuid = str(uuid.UUID(volume_uuid)).upper()
    cursor, end, nonzero = 32 + count * 16, 0, 0
    digest = hashlib.sha256()
    zeros = bytes(1 << 20)

    def zero_run(length):
        while length:
            n = min(length, len(zeros))
            digest.update(memoryview(zeros)[:n])
            length -= n

    for index in range(count):
        at, size = struct.unpack_from('<QQ', data, 32 + index * 16)
        if (
            not size
            or (at | size) % PAGE
            or at < end
            or at > logical
            or size > logical - at
            or size > len(data) - cursor
        ):
            raise ValueError('Invalid packed extent')
        zero_run(at - end)
        chunk = memoryview(data)[cursor : cursor + size]
        digest.update(chunk)
        nonzero += sum(any(chunk[i : i + PAGE]) for i in range(0, size, PAGE))
        cursor += size
        end = at + size
    if cursor != len(data) or nonzero * PAGE > RESIDENT_LIMIT:
        raise ValueError('Trailing input or resident seed cap exceeded')
    zero_run(logical - end)
    return dict(
        expected_volume_uuid=canonical_uuid,
        encoded_bytes=len(data),
        encoded_sha256=hashlib.sha256(data).hexdigest(),
        logical_bytes=logical,
        logical_sha256=digest.hexdigest(),
        nonzero_pages=nonzero,
    )


def seed_header(metadata):
    def array(value):
        return ','.join('0x' + value[i : i + 2] for i in range(0, len(value), 2))

    return '\n'.join(
        [
            '// Generated by build-native-ram-block.py from the exact recorded seed.',
            '#pragma once',
            '#include <stdint.h>',
            'constexpr uint64_t kNativeDataSeedEncodedBytes = {}ULL;'.format(metadata['encoded_bytes']),
            'constexpr uint64_t kNativeDataSeedLogicalBytes = {}ULL;'.format(metadata['logical_bytes']),
            'constexpr uint64_t kNativeDataSeedNonzeroPages = {}ULL;'.format(metadata['nonzero_pages']),
            'constexpr char kNativeDataSeedUUID[] = "{}";'.format(metadata['expected_volume_uuid']),
            'constexpr uint8_t kNativeDataSeedEncodedSHA256[32] = {{{}}};'.format(array(metadata['encoded_sha256'])),
            'constexpr uint8_t kNativeDataSeedLogicalSHA256[32] = {{{}}};'.format(array(metadata['logical_sha256'])),
            '',
        ]
    )


if __name__ == '__main__':
    seed, volume_uuid, out = sys.argv[1:]
    Path(out).write_text(seed_header(seed_metadata(seed, volume_uuid)))
