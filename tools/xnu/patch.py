"""ioswitch's XNU changes as one patch in the main repository (replaces scripts/xnu-patch.sh).

The XNU working repository (default: out/native-a57/root-v1/tree/.cache/xnu-work) is apple's xnu-10063.141.1 at BASE
with our changes committed on its branch `ioswitch`. The build never reads it: Bazel applies
out/native-a57/root-v1/tree/patches/xnu-ioswitch.diff to the pinned tarball (MODULE.bazel @xnu). So after committing
XNU edits there:

    bazel run //xnu:patch_export            # write the patch from the branch (refuses uncommitted XNU edits)
    bazel run //xnu:patch_check             # exit 1 if the patch is not what export would write
    bazel run //xnu:patch_apply -- <dir>    # a fresh xnu-10063.141.1 checkout -> branch ioswitch with the patch

Each takes --xnu <checkout> to use another working repository.
"""
import argparse
import os
import subprocess
import sys
from pathlib import Path

BASE = "d8b8029"   # xnu-10063.141.1, the checkout's first commit
PATCH = "out/native-a57/root-v1/tree/patches/xnu-ioswitch.diff"
DEFAULT_XNU = "out/native-a57/root-v1/tree/.cache/xnu-work"


def git(xnu, *args, **kwargs):
    return subprocess.run(["git", "-C", str(xnu), *args], check=True, capture_output=True, text=True, **kwargs).stdout


def render(xnu):
    head = git(xnu, "rev-parse", "--short", "ioswitch").strip()
    header = ("# ioswitch's changes to apple-oss-distributions/xnu tag xnu-10063.141.1 (base commit {} in .cache/xnu-work).\n"
              "# Generated by `bazel run //xnu:patch_export` from branch ioswitch at {}; apply with\n"
              "# `bazel run //xnu:patch_apply -- <xnu checkout>`. Do not edit by hand.\n").format(BASE, head)
    return header + git(xnu, "diff", "--binary", "--full-index", BASE, "ioswitch")


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("command", choices=["export", "check", "apply"])
    parser.add_argument("target", nargs="?", help="apply: the xnu-10063.141.1 checkout")
    parser.add_argument("--xnu", help="the XNU working repository (default: the tree's .cache/xnu-work)")
    args = parser.parse_args()
    workspace = Path(os.environ.get("BUILD_WORKSPACE_DIRECTORY", "."))
    patch = workspace / PATCH
    xnu = Path(args.xnu) if args.xnu else workspace / DEFAULT_XNU
    if args.command == "export":
        if git(xnu, "status", "--porcelain").strip():
            sys.exit("{} has uncommitted changes: commit them on branch ioswitch first".format(xnu))
        text = render(xnu)
        tmp = patch.with_suffix(".diff.new")
        tmp.write_text(text)
        tmp.replace(patch)
        print("{}: {}".format(patch, git(xnu, "diff", "--shortstat", BASE, "ioswitch").strip()))
    elif args.command == "check":
        if render(xnu) != patch.read_text():
            sys.exit("{} is out of date: run bazel run //xnu:patch_export".format(patch))
        print("{} matches {} branch ioswitch".format(patch, xnu))
    else:
        target = Path(args.target or sys.exit("usage: patch_apply -- <xnu-10063.141.1 checkout>"))
        if git(target, "status", "--porcelain").strip():
            sys.exit("{} is not clean".format(target))
        git(target, "switch", "-c", "ioswitch")
        git(target, "apply", "--index", "--whitespace=nowarn", str(patch))
        git(target, "commit", "-q", "-m", "ioswitch: Switch (Tegra X1) port changes (from {})".format(PATCH))
        print("applied to {} on branch ioswitch".format(target))


if __name__ == "__main__":
    main()
