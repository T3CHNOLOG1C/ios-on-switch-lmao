/*
 * a64x_classify.c: which ARMv8.1+ class an instruction word is in (A64X_OK if a Cortex-A57 runs it).
 * Encodings from the Arm ARM (DDI 0487), cross-checked against LLVM's disassembler
 * (tools/oracle.py: `llvm-mc -mcpu=apple-m4` with and without each feature).
 */
#include "a64x.h"

#define BITS(w, hi, lo) (((w) >> (lo)) & ((1u << ((hi) - (lo) + 1)) - 1))
#define BIT(w, n)       (((w) >> (n)) & 1u)

bool a64x_is_pac_hint(uint32_t w)
{
    /* HINT #imm: 1101 0101 0000 0011 0010 CRm op2 11111; PAC hints are CRm=0001 op2=000/010/100/110,
	 * CRm=0011 op2=000..111 (PACIAZ/PACIASP/...), and XPACLRI CRm=0000 op2=111. */
    if ((w & 0xFFFFF01F) != 0xD503201F) {
        return false;
    }
    uint32_t imm = BITS(w, 11, 5);
    return imm == 7 || imm == 8 || imm == 10 || imm == 12 || imm == 14 || (imm >= 24 && imm <= 31);
}

static enum a64x_class classify_scalar_fp(uint32_t w)
{
    /* scalar FP / FP<->int: (w & 0x5E000000) == 0x1E000000 */
    uint32_t ftype = BITS(w, 23, 22);
    if ((w & 0xFFFFFC00) == 0x1E7E0000) {
        return A64X_JSCVT;
    }
    /* S (bit 29) must be 0; M (bit 31) must be 0 except in the conversions (bit 24 = 0 and either bit 21 = 0,
	 * fixed point, or bits 15:10 = 000000, integer). Anything else is unallocated on every CPU (data). */
    if (BIT(w, 29)) {
        return A64X_OK;
    }
    bool conversion = !BIT(w, 24) && (!BIT(w, 21) || BITS(w, 15, 10) == 0);
    if (BIT(w, 31) && !conversion) {
        return A64X_OK;
    }
    /* FP data-processing (1 source): M 0 S 11110 ftype 1 opcode(6) 10000 Rn Rd */
    if ((w & 0x5F207C00) == 0x1E204000) {
        uint32_t opcode = BITS(w, 20, 15);
        if (ftype == 3) {
            /* FCVT Sd,Hn and FCVT Dd,Hn are ARMv8.0 */
            if (opcode == 4 || opcode == 5) {
                return A64X_OK;
            }
            return A64X_FP16;
        }
        if (ftype == 1 && opcode == 6) {
            return A64X_I8MM_BF16; /* BFCVT */
        }
        if (opcode >= 16 && opcode <= 19 && ftype <= 1) {
            return A64X_FRINTTS;
        }
        return A64X_OK;
    }
    if (ftype == 3) {
        /* Every other scalar FP/conversion form with ftype=11 is half precision (FEAT_FP16). The
		 * FMOV Xd, Vn.D[1] forms use ftype=10. */
        return A64X_FP16;
    }
    return A64X_OK;
}

static enum a64x_class classify_simd(uint32_t w)
{
    /* AdvSIMD three same extra (vector / scalar): all of it is ARMv8.1+ */
    if ((w & 0x9F208400) == 0x0E008400 || (w & 0xDF208400) == 0x5E008400) {
        uint32_t u = BIT(w, 29), opcode = BITS(w, 14, 11), size = BITS(w, 23, 22);
        if (opcode <= 1 && u) {
            return A64X_RDM;
        }
        if (opcode == 2) {
            return A64X_DOTPROD;
        }
        /* FCMLA opcode 10xx, FCADD 11x0, vector only, size H/S/D with D only as 2D; 1101 and 1111 are BF16/I8MM
		 * (BFMMLA, BFDOT, BFMLALB/T) */
        if (u && !BIT(w, 28) && size != 0 && !(size == 3 && !BIT(w, 30)) &&
            ((opcode & 0xC) == 0x8 || (opcode & 0xD) == 0xC)) {
            return A64X_FCMA;
        }
        return A64X_I8MM_BF16;
    }
    /* AdvSIMD three same (FP16): 0 Q U 01110 a 10 Rm 00 opcode 1 Rn Rd; scalar: 01 U 11110 a 10 Rm 00 opc 1 */
    if ((w & 0x9F60C400) == 0x0E400400 || (w & 0xDF60C400) == 0x5E400400) {
        return A64X_FP16;
    }
    /* AdvSIMD two-reg misc (FP16) vector / scalar */
    if ((w & 0x9F7E0C00) == 0x0E780800 || (w & 0xDF7E0C00) == 0x5E780800) {
        return A64X_FP16;
    }
    /* across lanes FP16: FMAXNMV/FMINNMV/FMAXV/FMINV H (bit 23 = o1 picks min/max, bit 22 is 0) */
    if ((w & 0xBF7FFC00) == 0x0E30C800 || (w & 0xBF7FFC00) == 0x0E30F800) {
        return A64X_FP16;
    }
    /* scalar pairwise FP16: FMAXNMP/FMINNMP, FMAXP/FMINP (bit 23 = o1), FADDP (o1 = 0 only); U=0, bit 22 is 0 */
    if ((w & 0xFF7FFC00) == 0x5E30C800 || (w & 0xFFFFFC00) == 0x5E30D800 || (w & 0xFF7FFC00) == 0x5E30F800) {
        return A64X_FP16;
    }
    /* FMOV (vector, immediate), half: 0 Q 0 0111100000 abc 1111 1 1 defgh Rd */
    if ((w & 0xBFF8FC00) == 0x0F00FC00) {
        return A64X_FP16;
    }
    /* vector/scalar x indexed element: 0 Q U 01111 size L M Rm opcode H 0 Rn Rd / 01 U 11111 ... */
    if ((w & 0x9F000400) == 0x0F000000 || (w & 0xDF000400) == 0x5F000000) {
        uint32_t u = BIT(w, 29), size = BITS(w, 23, 22), opcode = BITS(w, 15, 12);
        bool scalar = BIT(w, 30) && BIT(w, 28);
        if (u && (opcode == 0xD || opcode == 0xF)) {
            return A64X_RDM;
        }
        if (size == 0 && (opcode == 1 || opcode == 5 || opcode == 9)) {
            return A64X_FP16;
        }
        if (!scalar && opcode == 0xE) {
            return A64X_DOTPROD;
        }
        if (!scalar && opcode == 0xF && !u) {
            return A64X_I8MM_BF16; /* SUDOT/USDOT/BFDOT/BFMLAL by element */
        }
        /* FCMLA (by element): 4H/8H with index H:L (H only for 8H), 4S with index H (L = 0) */
        if (!scalar && u && (opcode & 9) == 1 &&
            ((size == 1 && (BIT(w, 30) || !BIT(w, 11))) || (size == 2 && BIT(w, 30) && !BIT(w, 21)))) {
            return A64X_FCMA;
        }
        if (size == 2 && ((!u && (opcode == 0 || opcode == 4)) || (u && (opcode == 8 || opcode == 0xC)))) {
            return A64X_FHM;
        }
        return A64X_OK;
    }
    /* AdvSIMD three same: FMLAL/FMLSL (vector): 0 Q U 01110 x 0 1 Rm opcode 1 Rn Rd */
    if ((w & 0x9F200400) == 0x0E200400) {
        uint32_t u = BIT(w, 29), opcode = BITS(w, 15, 11), sizebit22 = BIT(w, 22);
        if (!sizebit22 && ((!u && opcode == 0x1D) || (u && opcode == 0x19))) {
            return A64X_FHM;
        }
        return A64X_OK;
    }
    /* AdvSIMD shift by immediate, FP16 fixed-point conversions: immh = 001x, opcode 11100/11111 */
    if ((w & 0x9F800400) == 0x0F000400 || (w & 0xDF800400) == 0x5F000400) {
        uint32_t immh = BITS(w, 22, 19), opcode = BITS(w, 15, 11);
        if ((immh >> 1) == 1 && (opcode == 0x1C || opcode == 0x1F)) {
            return A64X_FP16;
        }
        return A64X_OK;
    }
    /* AdvSIMD two-reg misc: FRINT32/64 vector (opcode 1111x, size 0x) and BFCVTN */
    if ((w & 0x9F3E0C00) == 0x0E200800) {
        uint32_t u = BIT(w, 29), size = BITS(w, 23, 22), opcode = BITS(w, 16, 12);
        if ((opcode == 0x1E || opcode == 0x1F) && size <= 1) {
            return A64X_FRINTTS;
        }
        if (!u && opcode == 0x16 && size == 2) {
            return A64X_I8MM_BF16; /* BFCVTN */
        }
        (void)u;
        return A64X_OK;
    }
    return A64X_OK;
}

static bool sysreg_v80_el0(uint32_t op0, uint32_t op1, uint32_t crn, uint32_t crm, uint32_t op2)
{
    if (op0 == 3 && op1 == 3) {
        switch (crn) {
        case 0:
            return crm == 0 && (op2 == 1 || op2 == 7); /* CTR, DCZID */
        case 4:
            return (crm == 2 && op2 <= 1) || (crm == 4 && op2 <= 1) || crm == 5; /* NZCV DAIF FPCR FPSR DSPSR/DLR */
        case 9:
            return crm >= 12; /* PMU */
        case 13:
            return crm == 0 && (op2 == 2 || op2 == 3); /* TPIDR(RO)_EL0 */
        case 14:
            return (crm == 0 && op2 <= 2) || (crm >= 2 && crm <= 3) || crm >= 8; /* CNT*, PMEV* */
        default:
            return false;
        }
    }
    if (op0 == 2 && op1 == 3) {
        return true; /* debug comms channel */
    }
    if (op0 == 3 && op1 == 0 && crn == 0) {
        return true; /* ID registers: an EL0 read traps on v8.0 and on A12 alike (not a translation issue) */
    }
    return false;
}

enum a64x_class a64x_classify_slow(uint32_t w)
{
    uint32_t top = w >> 24;

    /* Loads and stores: op0 x1x0 */
    if ((w & 0x0A000000) == 0x08000000) {
        /* atomic memory operations: size 111 0 00 A R 1 Rs o3 opc 00 Rn Rt */
        if ((w & 0x3F200C00) == 0x38200000) {
            uint32_t o3 = BIT(w, 15), opc = BITS(w, 14, 12);
            if (!o3) {
                return A64X_LSE_LDOP;
            }
            if (opc == 0) {
                return A64X_LSE_SWP;
            }
            if (opc == 4 && BIT(w, 23) && !BIT(w, 22) && BITS(w, 20, 16) == 31) {
                return A64X_RCPC_LDAPR;
            }
            return A64X_LSE_OTHER;
        }
        /* LDRAA/LDRAB: 11 111 0 00 M S 1 imm9 W 1 Rn Rt */
        if ((w & 0xFF200400) == 0xF8200400) {
            return A64X_PAC_LDRA;
        }
        /* exclusive / ordered: size 001000 o2 L o1 Rs o0 Rt2 Rn Rt */
        if ((w & 0x3F000000) == 0x08000000) {
            if ((w & 0x3FA07C00) == 0x08A07C00) {
                return A64X_LSE_CAS;
            }
            if ((w & 0xBFA07C00) == 0x08207C00) {
                return A64X_LSE_CASP;
            }
            if ((w & 0x3FBFFC00) == 0x089F7C00) {
                return A64X_LOR; /* STLLR/LDLAR (L is bit 22, masked out) */
            }
            return A64X_OK;
        }
        /* MTE tag loads/stores: 11011001 opc 1 imm9 op2 Rn Rt */
        if ((w & 0xFF200000) == 0xD9200000) {
            return A64X_MTE;
        }
        /* LDAPUR/STLUR (FEAT_LRCPC2): size 011001 opc 0 imm9 00 Rn Rt */
        if ((w & 0x3F200C00) == 0x19000000) {
            return A64X_RCPC2;
        }
        return A64X_OK;
    }

    /* Data processing, scalar FP and AdvSIMD: op0 x111 */
    if ((w & 0x0E000000) == 0x0E000000) {
        if ((w & 0x5E000000) == 0x1E000000) {
            return classify_scalar_fp(w);
        }
        if (top == 0xCE) {
            return A64X_SHA3_SM;
        }
        return classify_simd(w);
    }

    /* Branches, exception generation, system: op0 101x */
    if ((w & 0x1C000000) == 0x14000000) {
        if (top == 0xD6 || top == 0xD7) {
            if (w == 0xD65F0BFF || w == 0xD65F0FFF) {
                return A64X_PAC_RET;
            }
            if (w == 0xD69F0BFF || w == 0xD69F0FFF) {
                return A64X_PAC_ERET;
            }
            /* BRAA/BRAB (Z=1, Rm) and BRAAZ/BRABZ (Z=0, Rm=11111) */
            if ((w & 0xFEFFF800) == 0xD61F0800) {
                if (!BIT(w, 24) && BITS(w, 4, 0) != 31) {
                    return A64X_OK; /* unallocated on every CPU */
                }
                return A64X_PAC_BR;
            }
            if ((w & 0xFEFFF800) == 0xD63F0800) {
                if (!BIT(w, 24) && BITS(w, 4, 0) != 31) {
                    return A64X_OK;
                }
                return A64X_PAC_BLR;
            }
            return A64X_OK;
        }
        if (top == 0xD5) {
            if (w == 0xD50330FF) {
                return A64X_SB;
            }
            /* MSR (immediate): 1101 0101 0000 0 op1 0100 CRm op2 11111 */
            if ((w & 0xFFF8F01F) == 0xD500401F) {
                uint32_t op1 = BITS(w, 18, 16), op2 = BITS(w, 7, 5), crm = BITS(w, 11, 8);
                if ((op1 == 0 && op2 == 5) || (op1 == 3 && (op2 == 6 || op2 == 7))) {
                    return A64X_OK; /* SPSel, DAIFSet, DAIFClr */
                }
                if (op1 == 0 && crm == 0 && op2 <= 2) {
                    return A64X_FLAGM; /* CFINV, XAFLAG, AXFLAG */
                }
                return A64X_PSTATE;
            }
            /* SYS (L=0, op0=01): 1101 0101 0000 1 op1 CRn CRm op2 Rt */
            if ((w & 0xFFF80000) == 0xD5080000) {
                uint32_t op1 = BITS(w, 18, 16), crn = BITS(w, 15, 12), crm = BITS(w, 11, 8), op2 = BITS(w, 7, 5);
                if (op1 == 3 && crn == 7 && crm == 12 && op2 == 1) {
                    return A64X_DPB; /* DC CVAP */
                }
                if (op1 == 3 && crn == 7) {
                    if ((crm == 4 && op2 == 1) || (crm == 10 && op2 == 1) || (crm == 11 && op2 == 1) ||
                        (crm == 14 && op2 == 1) || (crm == 5 && op2 == 1)) {
                        return A64X_OK; /* DC ZVA/CVAC/CVAU/CIVAC, IC IVAU */
                    }
                    return A64X_SYS_NEW; /* DC CVADP, DC GVA/GZVA, CFP/DVP/CPP RCTX, ... */
                }
                return A64X_OK; /* EL1 maintenance (TLBI, AT, IC IALLU...): not translation business */
            }
            /* MRS/MSR (register): 1101 0101 00 L 1 o0 op1 CRn CRm op2 Rt */
            if ((w & 0xFFD00000) == 0xD5100000) {
                uint32_t op0 = 2 + BIT(w, 19), op1 = BITS(w, 18, 16), crn = BITS(w, 15, 12);
                uint32_t crm = BITS(w, 11, 8), op2 = BITS(w, 7, 5);
                if (op0 == 3 && crn == 15) {
                    return A64X_SYSREG_IMPDEF;
                }
                if (op0 == 3 && op1 == 3 && crn == 4 && crm == 2 && op2 >= 5) {
                    return A64X_SYSREG_NEW; /* DIT, SSBS, TCO */
                }
                if (op0 == 3 && op1 == 3 &&
                    ((crn == 2 && crm == 4) || (crn == 14 && crm == 0 && op2 >= 5) ||
                     (crn == 13 && crm == 0 && op2 == 5))) {
                    return A64X_SYSREG_NEW; /* RNDR(RS), CNT{P,V}CTSS, TPIDR2_EL0 */
                }
                (void)sysreg_v80_el0;
                return A64X_OK; /* EL1 registers and v8.0 EL0 registers */
            }
            return A64X_OK;
        }
        return A64X_OK;
    }

    /* SVE (op0 0010) and SME (op0 0000 with bit 31 set) */
    if ((w & 0x1E000000) == 0x04000000 || (w & 0x9E000000) == 0x80000000) {
        return A64X_SVE_SME;
    }
    /* Data processing, immediate: CSSC min/max immediate, MTE ADDG/SUBG */
    if ((w & 0x7FC00000) == 0x11C00000) {
        return A64X_CSSC;
    }
    if ((w & 0xBFC0C000) == 0x91800000) {
        return A64X_MTE;
    }

    /* Data processing, register: op0 x101 */
    if ((w & 0x0E000000) == 0x0A000000) {
        if (top == 0xDA) {
            if ((w & 0xFFFFC000) == 0xDAC10000) {
                return A64X_PAC_DP; /* PACIA..AUTDZB */
            }
            if ((w & 0xFFFFFBE0) == 0xDAC143E0) {
                return A64X_PAC_XPAC;
            }
            return A64X_OK;
        }
        if ((w & 0xFFE0FC00) == 0x9AC03000) {
            return A64X_PAC_PACGA;
        }
        /* data-processing (2 source) beyond v8.0: IRG/GMI/SUBP(S) (MTE), SMAX/UMAX/SMIN/UMIN (CSSC) */
        if ((w & 0x5FE00000) == 0x1AC00000) {
            uint32_t opcode = BITS(w, 15, 10), sf = BIT(w, 31), s = BIT(w, 29);
            if (sf && ((opcode == 0 && !s) || (opcode == 0 && s) || opcode == 4 || opcode == 5)) {
                return A64X_MTE;
            }
            if (!s && opcode >= 0x18 && opcode <= 0x1B) {
                return A64X_CSSC;
            }
        }
        /* data-processing (1 source): CTZ/CNT/ABS (CSSC) */
        if ((w & 0x7FFF0000) == 0x5AC00000) {
            uint32_t opcode = BITS(w, 15, 10);
            if (opcode >= 6 && opcode <= 8) {
                return A64X_CSSC;
            }
        }
        /* RMIF: 1 0 1 11010000 imm6 00001 Rn 0 mask */
        if ((w & 0xFFE07C10) == 0xBA000400) {
            return A64X_FLAGM;
        }
        /* SETF8/SETF16: 0 0 1 11010000 000000 sz 0010 Rn 0 1101 */
        if ((w & 0xFFFFBC1F) == 0x3A00080D) {
            return A64X_FLAGM;
        }
        return A64X_OK;
    }

    /* Reserved / UDF space: Apple AMX and GXF */
    if ((w & 0xFFFFF000) == 0x00201000) {
        return A64X_APPLE_UDF;
    }
    return A64X_OK;
}

