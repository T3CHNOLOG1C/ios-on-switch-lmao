static uint32_t *fb;

void ui_init(uint32_t *framebuffer)
{
    fb = framebuffer;
}

// Landscape (x, y) in the 720 x 1280 portrait buffer (the same mapping as boot/handoff/display.h).
static inline void pixel(uint32_t x, uint32_t y, uint32_t color)
{
    if (x < UI_WIDTH && y < UI_HEIGHT) {
        fb[(UI_WIDTH - 1 - x) * UI_HEIGHT + y] = color;
    }
}

void ui_rect(uint32_t x, uint32_t y, uint32_t w, uint32_t h, uint32_t color)
{
    for (uint32_t i = 0; i < w; i++) {
        for (uint32_t j = 0; j < h; j++) {
            pixel(x + i, y + j, color);
        }
    }
}

void ui_clear(void)
{
    for (uint32_t i = 0; i < UI_WIDTH * UI_HEIGHT; i++) {
        fb[i] = UI_BLACK;
    }
}

uint32_t ui_text(uint32_t x, uint32_t y, uint32_t scale, uint32_t color, const char *text)
{
    for (; *text; text++, x += 8 * scale) {
        uint8_t c = (uint8_t)*text;
        const uint8_t *glyph = &font[8 * ((c >= 32 && c <= 126 ? c : '?') - 32)];
        for (uint32_t row = 0; row < 8; row++) {
            for (uint32_t col = 0; col < 8; col++) {
                uint32_t on = glyph[row] >> col & 1;
                ui_rect(x + col * scale, y + row * scale, scale, scale, on ? color : UI_BLACK);
            }
        }
    }
    return x;
}

uint32_t ui_textf(uint32_t x, uint32_t y, uint32_t scale, uint32_t color, const char *fmt, ...)
{
    char line[160];
    va_list ap;
    va_start(ap, fmt);
    s_vprintf(line, fmt, ap);
    va_end(ap);
    line[sizeof(line) - 1] = 0;
    return ui_text(x, y, scale, color, line);
}

void ui_progress(uint32_t y, uint64_t done, uint64_t total)
{
    const uint32_t x = 140, w = 1000, h = 16;
    uint32_t filled = total ? (uint32_t)(done * w / total) : 0;
    ui_rect(x, y, filled, h, UI_WHITE);
    ui_rect(x + filled, y, w - filled, h, 0xFF3A3A3Cu);
    uint32_t mib = (uint32_t)(done >> 20), all = (uint32_t)(total >> 20);
    uint32_t percent = total ? (uint32_t)(done * 100 / total) : 0;
    ui_textf(x, y + h + 16, 3, UI_GREY, "%d of %d MB  (%d%%)   ", mib, all, percent);
}
